# 6. Bundle: exactly 3 non-empty files, ocr.txt has $ or fallback hint
# ---------------------------------------------------------------------------

def test_write_bundle_three_files_nonempty():
    """write_close_bundle emits close.json + lines.csv + ocr.txt, all non-empty."""
    from omni_one.packs.vision_close import write_close_bundle

    close = _demo_close()
    with tempfile.TemporaryDirectory() as tmp:
        paths = write_close_bundle(close, tmp)
        assert set(paths) == {"close.json", "lines.csv", "ocr.txt"}, paths
        files = sorted(Path(tmp).iterdir())
        assert len(files) == 3, [p.name for p in files]
        for name in ("close.json", "lines.csv", "ocr.txt"):
            content = Path(paths[name]).read_text(encoding="utf-8")
            assert content.strip(), f"{name} must be non-empty"
        # ocr.txt for the demo carries real $ amounts from the receipt.
        ocr_txt = Path(paths["ocr.txt"]).read_text(encoding="utf-8")
        assert ("$" in ocr_txt) or ("fallback" in ocr_txt.lower()), ocr_txt


def test_write_bundle_garbage_ocr_has_fallback_hint():
    """Garbage bundle still has 3 files; ocr.txt carries the fallback hint."""
    from omni_one.packs.vision_close import build_vision_close, write_close_bundle

    close = build_vision_close(b"not-an-image", filename="garbage.bin")
    with tempfile.TemporaryDirectory() as tmp:
        paths = write_close_bundle(close, tmp)
        assert len(list(Path(tmp).iterdir())) == 3
        ocr_txt = Path(paths["ocr.txt"]).read_text(encoding="utf-8")
        assert ocr_txt.strip(), "ocr.txt must never be empty"
        assert ("$" in ocr_txt) or ("fallback" in ocr_txt.lower()), ocr_txt
        # close.json round-trips and preserves the unreadable verdict.
        saved = json.loads(Path(paths["close.json"]).read_text(encoding="utf-8"))
        assert _verdict_label(saved) == "unreadable"


