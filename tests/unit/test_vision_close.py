# 5. Idempotency: same bytes -> same verdict + numbers
# ---------------------------------------------------------------------------

def test_idempotent_same_verdict_and_numbers():
    """Two builds from the same bytes agree on verdict, numbers, chart."""
    from omni_one.packs.vision_close import build_vision_close

    payload = _demo_bytes("receipt")
    first = build_vision_close(payload, filename=DEMO_FILENAME)
    second = build_vision_close(payload, filename=DEMO_FILENAME)
    assert _verdict_label(first) == _verdict_label(second)
    assert _verdict_rule(first) == _verdict_rule(second)
    assert first["numbers"] == second["numbers"]
    assert first["cogs_lines"] == second["cogs_lines"]
    assert first["chart"] == second["chart"]
    assert first["do_today"] == second["do_today"]
    assert first["citations"] == second["citations"]
    # sha_affix stable: same input hash prefix.
    assert first["meta"]["sha256"] == second["meta"]["sha256"]


def test_idempotent_garbage_stable():
    """Garbage input is idempotent too (unreadable twice, same shape)."""
    from omni_one.packs.vision_close import build_vision_close

    first = build_vision_close(b"not-an-image", filename="g.bin")
    second = build_vision_close(b"not-an-image", filename="g.bin")
    assert _verdict_label(first) == "unreadable"
    assert first["verdict"] == second["verdict"]
    assert first["numbers"] == second["numbers"] == []


