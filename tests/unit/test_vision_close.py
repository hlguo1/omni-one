# 3. Garbage bytes -> unreadable, never raises
# ---------------------------------------------------------------------------

def test_garbage_bytes_unreadable_no_raise():
    """b"not-an-image" degrades to verdict unreadable (no exception)."""
    from omni_one.packs.vision_close import build_vision_close

    close = build_vision_close(b"not-an-image", filename="garbage.bin")
    assert _verdict_label(close) == "unreadable", close["verdict"]
    assert _verdict_rule(close) in ("no_text_no_numbers", "empty_fallback")
    assert close["numbers"] == []
    assert close["cogs_lines"] == []
    assert close["chart"]["values"] == []
    assert len(close["do_today"]) == 3  # still actionable
    assert close["meta"]["bytes"] == len(b"not-an-image")
    # OCR text empty or whitespace-only for garbage.
    assert not close["ocr"]["text"].strip()


def test_garbage_bytes_many_shapes_no_raise():
    """Fuzz-ish: truncated PNG header, text-as-image, null bytes -> unreadable."""
    from omni_one.packs.vision_close import build_vision_close

    for payload in (b"\x89PNG", b"\xff\xd8\xff", b"\x00" * 64, b"hello world" * 10):
        close = build_vision_close(payload, filename="weird.bin")
        assert _verdict_label(close) in ("unreadable", "photo", "chart-like",
                                         "invoice-like"), close["verdict"]
        # The hard guarantee: never raises, always returns the contract keys.
        for key in ("meta", "ocr", "numbers", "verdict", "do_today", "citations"):
            assert key in close


