# 8. Payload hygiene: close.json never carries full image data
# ---------------------------------------------------------------------------

def test_close_json_never_contains_full_payload():
    """close.json text has no payload-key spelling, or only [omitted] values."""
    from omni_one.packs.vision_close import write_close_bundle

    close = _demo_close()
    with tempfile.TemporaryDirectory() as tmp:
        paths = write_close_bundle(close, tmp)
        raw = Path(paths["close.json"]).read_text(encoding="utf-8")
        lowered = raw.lower()
        # Either the payload-key spelling is absent (preferred — we use
        # chart_preview instead), or every occurrence is an [omitted] marker.
        assert ("base64" not in lowered) or ("[omitted]" in raw), raw[:500]
        # No single 400+ char token (encoded PNG blobs are ~10k+ chars).
        longest = max((len(tok) for tok in raw.split()), default=0)
        assert longest < 400, f"suspicious long token ({longest} chars) in close.json"


def test_evidence_details_trimmed_and_payload_free():
    """Every evidence detail is short and free of long encoded tokens."""
    close = _demo_close()
    assert close["evidence"], "expected at least one evidence step"
    for step in close["evidence"]:
        detail = str(step.get("detail", ""))
        assert len(detail) <= 210, step
        longest = max((len(tok) for tok in detail.split()), default=0)
        assert longest < 200, step


