def test_make_demo_image_kinds():
    """make_demo_image supports receipt + chart kinds; PNG bytes, 800x400."""
    from PIL import Image

    from omni_one.packs.vision_close import make_demo_image

    for kind in ("receipt", "chart"):
        data = make_demo_image(kind)
