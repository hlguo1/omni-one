"""Vision Close tests — PACK B (deterministic, offline, $0).

Covers ``src/omni_one/packs/vision_close.py`` only:
  - demo receipt fixture (PIL-generated, no Tesseract needed to GENERATE)
    yields numbers>0 and verdict invoice-like/chart-like (accept either,
    but the fixture is deterministic — see golden test below);
  - garbage bytes (b"not-an-image") -> verdict unreadable, never raises;
  - empty bytes -> verdict unreadable, never raises;
  - idempotency: same input -> same verdict + numbers;
  - write_close_bundle emits exactly 3 non-empty files
    (close.json + lines.csv + ocr.txt), ocr.txt carries $ or fallback hint;
  - close_to_csv parses with csv.DictReader and round-trips amounts;
  - close.json never carries a full image payload: the payload-key
    spelling is absent, or any residual value is the [omitted] marker.

Golden fixture (receipt_demo.png, generated by make_demo_image):
  lines: "ACME MARKET - RECEIPT" / "Tote Bag Canvas 50 x 4.00 200.00" /
         "Shipping 1 x 15.00 15.00" / "Tax $12.50" / "Total $227.50"
  numbers: line2=200.00, line3=15.00, line4=12.50, line5=227.50
  totals: lines_with_amounts=4, cogs_hits=2, sum=455.00, max=227.50
  verdict: invoice-like / rule invoice_signals (score 4/4).
  chart: labels [Total, Tote Bag Canvas, Shipping, Tax],
         values [227.5, 200.0, 15.0, 12.5].

All tests are offline and $0. Tesseract is used when present (OCR path);
when absent the parsers still run and garbage/empty inputs still yield
unreadable without raising. No test touches cli.py, client.py, api/, or
mcp_server.py.
"""

from __future__ import annotations

import csv
import io
import json
import tempfile
from pathlib import Path

import pytest


# ---------------------------------------------------------------------------
# Helpers (deterministic fixtures + verdict-shape tolerance)
# ---------------------------------------------------------------------------

DEMO_FILENAME = "receipt_demo.png"


def _demo_bytes(kind: str = "receipt") -> bytes:
    """Generate the demo fixture image (PIL only, deterministic)."""
    from omni_one.packs.vision_close import make_demo_image

    data = make_demo_image(kind)
    assert isinstance(data, bytes), type(data)
    assert len(data) > 1000, f"demo image suspiciously small: {len(data)}"
    # PNG magic — guards against accidental format regressions.
    assert data[:8] == b"\x89PNG\r\n\x1a\n", data[:8]
    return data


def _demo_close(filename: str = DEMO_FILENAME, lang: str = "eng") -> dict:
    """Build the golden demo close (receipt fixture)."""
    from omni_one.packs.vision_close import build_vision_close

    return build_vision_close(_demo_bytes("receipt"), filename=filename, lang=lang)


def _verdict_label(close: dict) -> str:
    """Accept verdict as dict {label,...} or plain string (forward-compat)."""
    verdict = close.get("verdict")
    if isinstance(verdict, dict):
        return str(verdict.get("label", ""))
    return str(verdict or "")


def _verdict_rule(close: dict) -> str:
    """Extract verdict rule ("" when verdict is a plain string)."""
    verdict = close.get("verdict")
    if isinstance(verdict, dict):
        return str(verdict.get("rule", ""))
    return ""


def _numbers_amounts(close: dict) -> list:
    """Sorted amounts from numbers[] for order-insensitive comparisons."""
    return sorted(float(n["amount"]) for n in close.get("numbers", []))


# ---------------------------------------------------------------------------
# 1. Demo receipt: numbers>0 and verdict invoice-like/chart-like
# ---------------------------------------------------------------------------

def test_demo_receipt_has_numbers_and_invoice_or_chart_verdict():
    """Demo receipt bundle has numbers>0 and an invoice/chart verdict.

    Accepts either invoice-like or chart-like (both mean "machine found
    money"), but the fixture is deterministic so the golden test below
    pins the exact label. Also checks the close shape: meta/ocr/numbers/
    cogs_lines/chart/evidence/verdict/do_today[3]/citations/cost $0.
    """
    close = _demo_close()

    # Shape: all contract keys present.
    for key in ("meta", "ocr", "numbers", "cogs_lines", "chart",
                "evidence", "verdict", "do_today", "citations", "totals"):
        assert key in close, f"missing close key: {key}"

    # Numbers: at least one amount extracted from the receipt lines.
    assert len(close["numbers"]) > 0, f"expected numbers>0, ocr={close['ocr']['text']!r}"
    for hit in close["numbers"]:
        assert set(("line_no", "text", "amount")) <= set(hit), hit
        assert isinstance(hit["line_no"], int) and hit["line_no"] >= 1
        assert isinstance(hit["amount"], (int, float)) and hit["amount"] > 0

    # Verdict: invoice-like or chart-like (deterministic fixture -> invoice).
    label = _verdict_label(close)
    assert label in ("invoice-like", "chart-like"), close["verdict"]
    assert _verdict_rule(close), "verdict must carry a rule"

    # do_today: exactly 3 non-empty actions.
    assert isinstance(close["do_today"], list) and len(close["do_today"]) == 3
    assert all(isinstance(a, str) and a.strip() for a in close["do_today"])

    # Citations: one per numbers hit, shaped <filename>:<line>.
    assert len(close["citations"]) == len(close["numbers"])
    for cite in close["citations"]:
        assert cite.startswith(DEMO_FILENAME + ":"), cite

    # Cost: $0 offline.
    assert close.get("cost_usd", 0.0) == 0.0
    assert close["meta"]["cost_usd"] == 0.0
    assert close["meta"]["free"] is True

    # OCR truncated to <=2000 chars in the bundle.
    assert len(close["ocr"]["text"]) <= 2000

    # Evidence trimmed: every detail <= ~210 chars, no payload blobs.
    assert 1 <= len(close["evidence"]) <= 6
    for step in close["evidence"]:
        assert "step" in step and "detail" in step, step
        assert len(str(step["detail"])) <= 210, step


# ---------------------------------------------------------------------------
# 2. Golden amounts for the receipt fixture (pins determinism)
# ---------------------------------------------------------------------------

def test_demo_receipt_golden_numbers_cogs_chart():
    """Pin the exact golden amounts so regressions are caught loudly.

    Fixture lines carry: 200.00 (Tote 50x4.00), 15.00 (Shipping 1x15.00),
    12.50 (Tax), 227.50 (Total). COGS hits: 2 (the two qty-x-unit lines).
    Chart: top numbers desc. Totals: sum 455.00, max 227.50.
    """
    close = _demo_close()

    # Exact verdict for this deterministic fixture.
    assert _verdict_label(close) == "invoice-like", close["verdict"]
    assert _verdict_rule(close) == "invoice_signals", close["verdict"]

    # Exact numbers (order-insensitive + per-line spot checks).
    assert _numbers_amounts(close) == [12.5, 15.0, 200.0, 227.5], close["numbers"]
    by_line = {n["line_no"]: n["amount"] for n in close["numbers"]}
    assert by_line.get(5) == 227.5, by_line  # Total line
    assert by_line.get(2) == 200.0, by_line  # Tote line (last-money, not 50)

    # COGS: the two "<qty> x <unit>" lines parse with qty/unit/total.
    cogs = close["cogs_lines"]
    assert len(cogs) == 2, cogs
    tote = next(h for h in cogs if h["line_no"] == 2)
    assert tote["qty"] == 50.0 and tote["unit"] == 4.0 and tote["total"] == 200.0
    assert tote["citation"] == f"{DEMO_FILENAME}:2"
    ship = next(h for h in cogs if h["line_no"] == 3)
    assert ship["qty"] == 1.0 and ship["unit"] == 15.0 and ship["total"] == 15.0

    # Chart: top numbers desc with de-numbered labels.
    chart = close["chart"]
    assert chart["values"] == [227.5, 200.0, 15.0, 12.5], chart
    assert chart["labels"][0] == "Total", chart
    assert any("Tote" in lb for lb in chart["labels"]), chart
    assert chart["top_n"] == 4

    # Totals math.
    assert close["totals"]["lines_with_amounts"] == 4
    assert close["totals"]["cogs_hits"] == 2
    assert close["totals"]["sum_amounts"] == pytest.approx(455.0)
    assert close["totals"]["max_amount"] == pytest.approx(227.5)
    assert close["totals"]["min_amount"] == pytest.approx(12.5)

    # Meta echoes the request.
    assert close["meta"]["filename"] == DEMO_FILENAME
    assert close["meta"]["bytes"] == len(_demo_bytes("receipt"))
    assert close["meta"]["lang"] == "eng"


